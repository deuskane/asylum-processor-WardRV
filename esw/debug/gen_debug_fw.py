import os

RESET_ADDR   = 0x80000000
DATA_ADDR    = 0x80001000   # counter @ +0, flag @ +4
MASK         = 0xFFFFFFFF

def i_type(imm, rs1, f3, rd, op):
    assert -2048 <= imm < 2048
    return ((imm & 0xFFF) << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op

def s_type(imm, rs2, rs1, f3, op=0x23):
    imm &= 0xFFF
    return ((imm >> 5) << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | ((imm & 0x1F) << 7) | op

def b_type(imm, rs2, rs1, f3, op=0x63):
    imm &= 0x1FFF
    return (((imm >> 12) & 1) << 31) | (((imm >> 5) & 0x3F) << 25) | (rs2 << 20) | (rs1 << 15) | \
           (f3 << 12) | (((imm >> 1) & 0xF) << 8) | (((imm >> 11) & 1) << 7) | op

def u_type(imm20, rd, op):
    return ((imm20 & 0xFFFFF) << 12) | (rd << 7) | op

def j_type(imm, rd, op=0x6F):
    imm &= 0x1FFFFF
    return (((imm >> 20) & 1) << 31) | (((imm >> 1) & 0x3FF) << 21) | (((imm >> 11) & 1) << 20) | \
           (((imm >> 12) & 0xFF) << 12) | (rd << 7) | op

PROG = [
    (0x00, u_type(DATA_ADDR >> 12, 10, 0x37), "lui     x10, 0x80001     # data area"),
    (0x04, i_type(0, 0, 0, 5, 0x13),          "addi    x5, x0, 0        # counter"),
    (0x08, i_type(0, 0, 0, 9, 0x13),          "addi    x9, x0, 0        # breakpoints"),
    (0x0C, i_type(1, 5, 0, 5, 0x13),          "addi    x5, x5, 1        # loop"),
    (0x10, s_type(0, 5, 10, 2),               "sw      x5, 0(x10)       # counter"),
    (0x14, i_type(4, 10, 2, 8, 0x03),         "lw      x8, 4(x10)       # flag"),
    (0x18, b_type(-12, 0, 8, 0),              "beq     x8, x0, loop"),
    (0x1C, 0x00100073,                        "ebreak                   # software breakpoint"),
    (0x20, i_type(1, 9, 0, 9, 0x13),          "addi    x9, x9, 1"),
    (0x24, s_type(4, 0, 10, 2),               "sw      x0, 4(x10)       # clear flag"),
    (0x28, j_type(-28, 0),                    "jal     x0, loop"),
]

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "debug_fw.hex"), "w") as f:
        for off, w, _ in PROG:
            f.write(f"{w & MASK:08x}\n")
    with open(os.path.join(here, "debug_fw.lst"), "w") as f:
        f.write("# Generated by gen_debug_fw.py - do not edit\n")
        for off, w, t in PROG:
            f.write(f"{RESET_ADDR + off:08x}:\t{w & MASK:08x}\t{t}\n")
    print(f"{len(PROG)} instructions")

if __name__ == "__main__":
    main()
