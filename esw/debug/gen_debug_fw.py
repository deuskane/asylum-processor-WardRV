# Description: Generate the firmware of the debug system test (sim_debug_system,
#              sim/tb_WardRV_debug.vhd) without RISC-V toolchain : writes
#              debug_fw.hex (one 32-bit word per line, loaded at 0x80000000)
#              and debug_fw.lst.
#
#              The program increments a counter in memory forever. When the
#              flag word is not zero, it executes an ebreak (software
#              breakpoint, test with dcsr.ebreakm = 1), counts it in x9 and
#              clears the flag. The addresses below are used by the testbench.
#
#              Usage : python3 gen_debug_fw.py   (in esw/debug)
