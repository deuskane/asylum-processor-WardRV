library ieee;
use     ieee.std_logic_1164.all;
use     ieee.numeric_std.all;

library asylum;
use     asylum.sbi_pkg.all;
use     asylum.WardRV_debug_pkg.all;
use     asylum.WardRV_dbg_rom_pkg.all;

entity WardRV_dbg_dm_mem is
  generic (
    PROGBUF_SIZE : natural := 2;
    DATA_COUNT   : natural := 2;
    IMPEBREAK    : boolean := true
  );
  port (
    -- Core access (debug mode)
    dbg_sbi_ini_i : in  dbg_sbi_ini_t;
    dbg_sbi_tgt_o : out dbg_sbi_tgt_t;

    -- Content provided by the DM
    abstract_i    : in  dbg_words_t(0 to DBG_ABSTRACT_SIZE-1);
    progbuf_i     : in  dbg_words_t(0 to DBG_PROGBUF_MAX-1);
    data_i        : in  dbg_words_t(0 to DBG_DATA_MAX-1);
    flag_go_i     : in  std_logic;
    flag_resume_i : in  std_logic;

    -- Core writes (combinational strobes)
    halted_o      : out std_logic;
    going_o       : out std_logic;
    resuming_o    : out std_logic;
    exception_o   : out std_logic;
    data_we_o     : out std_logic;
    data_idx_o    : out natural range 0 to DBG_DATA_MAX-1;
    data_wdata_o  : out std_logic_vector(31 downto 0)
  );
end entity WardRV_dbg_dm_mem;

architecture rtl of WardRV_dbg_dm_mem is

  -- Word index (byte offset / 4)
  constant WI_HALTED    : natural := DBG_OFFSET_HALTED    / 4;
  constant WI_GOING     : natural := DBG_OFFSET_GOING     / 4;
  constant WI_RESUMING  : natural := DBG_OFFSET_RESUMING  / 4;
  constant WI_EXCEPTION : natural := DBG_OFFSET_EXCEPTION / 4;
  constant WI_WHERETO   : natural := DBG_OFFSET_WHERETO   / 4;
  constant WI_ABSTRACT  : natural := DBG_OFFSET_ABSTRACT  / 4;
  constant WI_PROGBUF   : natural := DBG_OFFSET_PROGBUF   / 4;
  constant WI_DATA      : natural := DBG_OFFSET_DATA      / 4;
  constant WI_FLAGS     : natural := DBG_OFFSET_FLAGS     / 4;

  -- WHERETO : jump to the abstract command program
  constant WHERETO      : std_logic_vector(31 downto 0) := rv_jal(RV_X0, DBG_OFFSET_ABSTRACT - DBG_OFFSET_WHERETO);

  -- After the program buffer : implicit ebreak
  function progbuf_end return std_logic_vector is
  begin
    if IMPEBREAK then
      return RV_EBREAK;
    end if;
    return (31 downto 0 => '0');
  end function;

  signal wi    : natural range 0 to 2**(DBG_MEM_AWIDTH-2)-1;
  signal write : std_logic;

begin

  assert PROGBUF_SIZE <= DBG_PROGBUF_MAX
    report "WardRV_dbg_dm_mem : PROGBUF_SIZE must be <= 16" severity failure;
  assert not (IMPEBREAK and PROGBUF_SIZE = DBG_PROGBUF_MAX)
    report "WardRV_dbg_dm_mem : PROGBUF_SIZE = 16 needs IMPEBREAK = false (debug memory map)" severity failure;
  assert DATA_COUNT >= 1 and DATA_COUNT <= DBG_DATA_MAX
    report "WardRV_dbg_dm_mem : DATA_COUNT must be in 1..12" severity failure;

  wi    <= to_integer(unsigned(dbg_sbi_ini_i.addr(DBG_MEM_AWIDTH-1 downto 2)));
  write <= dbg_sbi_ini_i.cs and dbg_sbi_ini_i.we;

  --------------------------------------------------------------------
  -- Read (combinational, no wait state)
  --------------------------------------------------------------------
  process(all)
  begin
    dbg_sbi_tgt_o.rdata <= (others => '0');
    if    wi < DBG_ROM_LENGTH
    then
      dbg_sbi_tgt_o.rdata <= DBG_ROM(wi);
    elsif wi = WI_WHERETO
    then
      dbg_sbi_tgt_o.rdata <= WHERETO;
    elsif wi >= WI_ABSTRACT and wi < WI_ABSTRACT + DBG_ABSTRACT_SIZE
    then
      dbg_sbi_tgt_o.rdata <= abstract_i(wi - WI_ABSTRACT);
    elsif wi >= WI_PROGBUF  and wi < WI_PROGBUF + PROGBUF_SIZE
    then
      dbg_sbi_tgt_o.rdata <= progbuf_i(wi - WI_PROGBUF);
    elsif wi >= WI_PROGBUF  and wi < WI_PROGBUF + DBG_PROGBUF_MAX
    then
      dbg_sbi_tgt_o.rdata <= progbuf_end;
    elsif wi >= WI_DATA     and wi < WI_DATA + DATA_COUNT
    then
      dbg_sbi_tgt_o.rdata <= data_i(wi - WI_DATA);
    elsif wi = WI_FLAGS
    then
      dbg_sbi_tgt_o.rdata <= (31 downto 2 => '0') & flag_resume_i & flag_go_i;
    end if;
  end process;

  dbg_sbi_tgt_o.ready     <= dbg_sbi_ini_i.cs;
  dbg_sbi_tgt_o.info.name <= to_sbi_name("WardRV_dbg_mem");

  --------------------------------------------------------------------
  -- Write strobes
  --------------------------------------------------------------------
  halted_o     <= write when wi = WI_HALTED    else '0';
  going_o      <= write when wi = WI_GOING     else '0';
  resuming_o   <= write when wi = WI_RESUMING  else '0';
  exception_o  <= write when wi = WI_EXCEPTION else '0';

  data_we_o    <= write when wi >= WI_DATA and wi < WI_DATA + DATA_COUNT else '0';
  data_idx_o   <= wi - WI_DATA when wi >= WI_DATA and wi < WI_DATA + DATA_COUNT else 0;
  data_wdata_o <= dbg_sbi_ini_i.wdata;

end architecture rtl;
