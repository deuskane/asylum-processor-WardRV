-- Description:
-- Debug memory of the Debug Module : 32-bit SBI target (11-bit byte address)
-- seen by the core in debug mode at 0xFFFF_F800. No wait state (ready = cs),
-- combinational read. The core writes only full words (sw).
--   Offset | Content                                   | Core access
--   0x000  | ROM : halt entry                          | R
--   0x008  | ROM : exception entry                     | R
--   0x100  | HALTED / GOING / RESUMING / EXCEPTION     | W
--   0x200  | WHERETO : jal ABSTRACT                    | R
--   0x300  | ABSTRACT[0..7] (generated by the DM)      | R
--   0x340  | PROGBUF[0..PROGBUF_SIZE-1] then ebreak    | R
--   0x380  | DATA[0..DATA_COUNT-1]                     | R/W
--   0x400  | FLAGS (bit 0 go, bit 1 resume)            | R
-- The write strobes are combinational, the DM registers them.
